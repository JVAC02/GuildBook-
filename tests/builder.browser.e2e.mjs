import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const { chromium } = await import(process.env.GUILDBOOK_PLAYWRIGHT || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.GUILDBOOK_BROWSER ? { executablePath: process.env.GUILDBOOK_BROWSER } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
page.setDefaultTimeout(5000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const base = process.env.GUILDBOOK_URL || 'http://127.0.0.1:4173/';
const screenshots = resolve(process.env.GUILDBOOK_SCREENSHOTS_DIR || 'screenshots');
await mkdir(screenshots, { recursive: true });
const shot = name => page.screenshot({ path: resolve(screenshots, name), fullPage: true });
const overflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);

try {
  await page.goto(base);
  await page.getByRole('button', { name: 'Abrir Dipirona' }).waitFor();
  const nav = await page.locator('.desktop-nav [data-view]').evaluateAll(buttons => buttons.map(button => button.dataset.view));
  assert.deepEqual(nav, ['home', 'medications', 'builder', 'favorites']);

  await page.getByRole('button', { name: 'Abrir Dipirona' }).click();
  await page.locator('[data-presentation=\"dip-1000\"]').click();
  assert.equal(await page.getByText('Texto para prescrição').count(), 0);
  assert.equal(await page.locator('#add-builder').isEnabled(), false);
  await page.locator('#dispense-choice').selectOption('package:10');
  await page.getByRole('button', { name: /Adicionar ao montador/ }).click();
  assert.match(await page.locator('#toast').innerText(), /Adicionado ao montador/);
  assert.match(await page.locator('.desktop-nav [data-view="builder"]').innerText(), /1/);
  await page.getByRole('button', { name: /Adicionar ao montador/ }).click();
  assert.match(await page.locator('#toast').innerText(), /Atualizado no montador/);

  await page.locator('.desktop-nav [data-view="medications"]').click();
  await page.getByRole('button', { name: 'Abrir Cetoprofeno' }).click();
  await page.locator('[data-presentation=\"keto-100\"]').click();
  await page.locator('#duration').fill('5');
  await page.getByRole('button', { name: /Adicionar ao montador/ }).click();
  await page.locator('.desktop-nav [data-view="builder"]').click();
  assert.equal(await page.locator('.builder-item').count(), 2);
  await page.locator('.desktop-nav [data-view="home"]').click();
  assert.match(await page.locator('.desktop-nav [data-view="builder"]').innerText(), /2/);
  await page.locator('.desktop-nav [data-view="favorites"]').click();
  assert.match(await page.locator('.desktop-nav [data-view="builder"]').innerText(), /2/);
  await page.locator('.desktop-nav [data-view="builder"]').click();
  assert.equal(await page.locator('.builder-item').count(), 2);
  const preview = await page.locator('#builder-preview').textContent();
  assert.match(preview, /^RECEITUÁRIO SIMPLES/);
  assert.match(preview, /PRESCRIÇÃO:/);
  assert.doesNotMatch(preview, /CNES:|VIA DIGITAL/);
  assert.match(preview, /DIPIRONA 1 G -+ 10 CP/);
  assert.match(preview, /CETOPROFENO 100 MG -+ 20 CP/);
  assert.doesNotMatch(preview, /QTDE A DEFINIR/);
  assert.doesNotMatch(preview, /CETOPROFENO 100 MG — COMPRIMIDO ENTÉRICO/);
  assert.doesNotMatch(preview, /Quantidade:/i);
  await shot('10-desktop-montador.png');
  await page.setViewportSize({ width: 390, height: 844 });
  await overflow();
  await shot('11-mobile-montador.png');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('#patient-name').fill('Maria da Silva');
  await page.locator('#issuer-options summary').click();
  await page.locator('#doctor-name').fill('Dra. Ana');
  await page.locator('#doctor-crm').fill('12345');
  await page.locator('#doctor-uf').fill('SP');
  await page.locator('#service-name').fill('Clínica A');
  await page.locator('#service-cnes').fill('9876');
  await page.locator('#issued-at').fill('2026-09-27');
  assert.match(await page.locator('#builder-preview').textContent(), /PACIENTE: Maria da Silva/);
  assert.match(await page.locator('#builder-preview').textContent(), /NOME DO\(A\) MÉDICO\(A\): Dra\. Ana\nCRM: 12345\s+UF: SP/);
  assert.match(await page.locator('#builder-preview').textContent(), /LOCAL DE ATENDIMENTO: Clínica A.*CNES: 9876/);
  assert.match(await page.locator('#builder-preview').textContent(), /DATA DE EMISSÃO: 27\/09\/2026/);
  const previewWithName = await page.locator('#builder-preview').textContent();
  await page.locator('#copy-builder').click();
  assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n'), previewWithName.replace(/\r\n/g, '\n'));
  await page.reload();
  await page.locator('.builder-item').first().waitFor();
  assert.equal(await page.locator('.builder-item').count(), 2);
  assert.equal(await page.locator('#patient-name').inputValue(), '');
  assert.equal(await page.locator('#doctor-name').inputValue(), '');
  assert.doesNotMatch(JSON.stringify(await page.evaluate(() => localStorage)), /Maria da Silva|Dra\. Ana|Clínica A/);
  await page.locator('.desktop-nav [data-view="medications"]').click();
  await page.getByRole('button', { name: 'Abrir Cetoprofeno' }).click();
  await page.locator('[data-presentation=\"keto-gel\"]').click();
  await page.locator('#dispense-choice').selectOption('package:30');
  await page.locator('#add-builder').click();
  await page.locator('.desktop-nav [data-view="builder"]').click();
  assert.equal(await page.locator('.builder-item').count(), 3);
  assert.match(await page.locator('#builder-preview').textContent(), /USO TÓPICO/);
  await page.locator('.builder-item').first().getByRole('button', { name: 'Editar' }).click();
  await page.locator('.builder-item').first().locator('input[name="quantity"]').fill('20');
  await page.locator('.builder-item').first().getByRole('button', { name: 'Salvar' }).click();
  const alignedLines = (await page.locator('#builder-preview').textContent()).split('\n');
  const dipLine = alignedLines.find(line => line.includes('DIPIRONA 1 G'));
  const ketoLine = alignedLines.find(line => line.includes('CETOPROFENO 100 MG'));
  assert.match(dipLine, /DIPIRONA 1 G -+ 20 CP/);
  assert.equal(dipLine.indexOf('20 CP'), ketoLine.indexOf('20 CP'));
  await shot('13-desktop-quantidades-alinhadas.png');
  await page.setViewportSize({ width: 390, height: 844 });
  await overflow();
  await shot('14-mobile-quantidades-alinhadas.png');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('.builder-item').first().getByRole('button', { name: 'Remover' }).click();
  assert.equal(await page.locator('.builder-item').count(), 2);
  await page.locator('#patient-name').fill('Maria da Silva');
  await page.locator('#issuer-options summary').click();
  await page.locator('#doctor-name').fill('Dra. Ana');
  await page.locator('#doctor-crm').fill('12345');
  await page.locator('#doctor-uf').fill('SP');
  await page.locator('#service-name').fill('Clínica A');
  await page.locator('#service-cnes').fill('9876');
  await page.locator('#service-address').fill('Rua Exemplo, 100');
  await page.locator('#service-neighborhood').fill('Centro');
  await page.locator('#service-city').fill('São Paulo');
  await page.locator('#service-uf').fill('SP');
  await page.locator('#service-phone').fill('(11) 3333-3333');
  await page.locator('#issued-at').fill('2026-09-27');
  await page.evaluate(() => { window.__printed = false; window.print = () => { window.__printed = true; }; });
  await page.locator('#print-builder').click();
  assert.equal(await page.evaluate(() => window.__printed), true);
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.site-header').evaluate(node => getComputedStyle(node).display), 'none');
  assert.equal(await page.locator('.builder-actions').evaluate(node => getComputedStyle(node).display), 'none');
  assert.equal(await page.locator('.builder-item').first().evaluate(node => getComputedStyle(node).visibility), 'hidden');
  assert.equal(await page.locator('#issuer-options').evaluate(node => getComputedStyle(node).display), 'none');
  assert.equal(await page.locator('.rx-body').evaluate(node => getComputedStyle(node).flexGrow), '1');
  const printedPdf = await page.pdf({ format: 'A4' });
  assert.equal(printedPdf.subarray(0, 4).toString(), '%PDF');
  if (process.env.GUILDBOOK_PRINT_QA_PDF) await writeFile(process.env.GUILDBOOK_PRINT_QA_PDF, printedPdf);
  await shot('12-impressao-montador.png');
  await page.emulateMedia({ media: 'screen' });
  await overflow();
  await page.setViewportSize({ width: 390, height: 844 });
  await overflow();
  assert.equal(await page.locator('.mobile-nav [data-view="builder"]').count(), 1);
  await page.once('dialog', dialog => dialog.accept());
  await page.locator('#clear-builder').click();
  assert.equal(await page.locator('.builder-item').count(), 0);
  await page.reload();
  assert.equal(await page.locator('.builder-item').count(), 0);
  await page.goto(pathToFileURL(resolve('GuildBook-Core-v7.html')).href);
  await page.getByRole('button', { name: 'Abrir Dipirona' }).click();
  await page.locator('[data-presentation=\"dip-1000\"]').click();
  await page.locator('#dispense-choice').selectOption('package:10');
  await page.locator('#add-builder').click();
  await page.locator('.mobile-nav [data-view="builder"]').click();
  assert.equal(await page.locator('.builder-item').count(), 1);
  assert.match(await page.locator('#builder-preview').textContent(), /DIPIRONA 1 G/);
  assert.deepEqual(errors, []);
  console.log('Montador E2E: fluxo, persistência, cópia, edição, remoção, impressão e responsividade passaram.');
} finally { await browser.close(); }
